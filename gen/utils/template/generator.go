package template

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"os"
	pathpkg "path"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"sync"
	texttemplate "text/template"

	"github.com/hashicorp/hcl/v2"
	"github.com/hashicorp/hcl/v2/hclsyntax"
	"github.com/hashicorp/hcl/v2/hclwrite"

	"github.com/CiscoDevNet/terraform-provider-aci/v2/gen/utils/data"
	"github.com/CiscoDevNet/terraform-provider-aci/v2/gen/utils/logger"
	"github.com/CiscoDevNet/terraform-provider-aci/v2/gen/utils/manifest"
)

const (
	templatePath          = "gen/templates"
	generatedMarkerFormat = `%s generated by "gen/generator.go"; DO NOT EDIT.`

	modelTemplateName    = "model.go.tmpl"
	modelOutputDirectory = "internal/provider/models"
)

var genLogger = logger.InitializeLogger()

type Generator struct {
	dataStore *data.DataStore
	templates map[string]*texttemplate.Template
}

type TemplateContext struct {
	Class     *data.Class
	DataStore *data.DataStore
}

type renderJob struct {
	TemplateName string
	OutputPath   string
	Context      TemplateContext
}

func NewGenerator(dataStore *data.DataStore) (*Generator, error) {
	if dataStore == nil {
		return nil, fmt.Errorf("initialize template generator: data store is nil")
	}

	generator := &Generator{dataStore: dataStore}
	if err := generator.loadTemplates(); err != nil {
		return nil, err
	}

	return generator, nil
}

func (g *Generator) loadTemplates() error {
	genLogger.Debugf("Loading templates from: %s.", templatePath)
	entries, err := os.ReadDir(templatePath)
	if err != nil {
		return fmt.Errorf("read template directory %q: %w", templatePath, err)
	}

	g.templates = make(map[string]*texttemplate.Template)
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".tmpl") {
			continue
		}

		path := filepath.Join(templatePath, entry.Name())
		genLogger.Debugf("Loading template: %s.", path)
		contents, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("read template %q: %w", path, err)
		}

		parsedTemplate, err := parseTemplate(entry.Name(), contents)
		if err != nil {
			return fmt.Errorf("load template %q: %w", path, err)
		}
		g.templates[entry.Name()] = parsedTemplate
		genLogger.Debugf("Successfully loaded template: %s.", path)
	}

	genLogger.Debugf("Successfully loaded %d templates.", len(g.templates))
	return nil
}

func parseTemplate(templateName string, contents []byte) (*texttemplate.Template, error) {
	marker, err := generatedMarkerForPath(templateName)
	if err != nil {
		return nil, err
	}
	if firstLine(string(contents)) != marker {
		return nil, fmt.Errorf("must start with %q", marker)
	}

	parsedTemplate, err := texttemplate.New(templateName).Parse(string(contents))
	if err != nil {
		return nil, fmt.Errorf("parse template: %w", err)
	}
	return parsedTemplate, nil
}

func (g *Generator) Generate() error {
	genLogger.Trace("Building template render jobs")
	jobs := g.buildRenderJobs()
	genLogger.Trace("Building template render jobs complete")

	genLogger.Trace("Validating template render jobs")
	plannedFiles, err := g.validateRenderJobs(jobs)
	if err != nil {
		return fmt.Errorf("validate render jobs: %w", err)
	}
	plannedManifest := manifest.New(plannedFiles)
	genLogger.Trace("Validating template render jobs complete")

	genLogger.Trace("Loading managed files")
	managedFiles, err := manifest.Load()
	if err != nil {
		return fmt.Errorf("load managed files: %w", err)
	}
	genLogger.Trace("Loading managed files complete")

	genLogger.Trace("Deleting managed files")
	if err := managedFiles.DeleteManagedFiles(); err != nil {
		return fmt.Errorf("delete managed files: %w", err)
	}
	genLogger.Trace("Deleting managed files complete")

	genLogger.Trace("Rendering templates")
	if err := g.renderTemplates(jobs); err != nil {
		genLogger.Trace("Cleaning up outputs after failed template rendering")
		if cleanupErr := plannedManifest.DeleteManagedFiles(); cleanupErr != nil {
			return errors.Join(
				err,
				fmt.Errorf("clean up outputs after failed rendering: %w", cleanupErr),
			)
		}
		genLogger.Trace("Cleaning up outputs after failed template rendering complete")
		return err
	}
	genLogger.Trace("Rendering templates complete")

	genLogger.Trace("Writing managed files")
	if err := plannedManifest.Write(); err != nil {
		return fmt.Errorf("write managed files: %w", err)
	}
	genLogger.Trace("Writing managed files complete")

	return nil
}

func (g *Generator) buildRenderJobs() []renderJob {
	return g.buildModelRenderJobs()
}

func (g *Generator) buildModelRenderJobs() []renderJob {
	classNames := make([]string, 0, len(g.dataStore.Classes))
	for className := range g.dataStore.Classes {
		classNames = append(classNames, className)
	}
	sort.Strings(classNames)

	jobs := make([]renderJob, 0, len(classNames))
	for _, className := range classNames {
		class := g.dataStore.Classes[className]
		outputPath := pathpkg.Join(modelOutputDirectory, class.Name.String()+".go")
		jobs = append(jobs, renderJob{
			TemplateName: modelTemplateName,
			OutputPath:   outputPath,
			Context: TemplateContext{
				Class:     &class,
				DataStore: g.dataStore,
			},
		})
	}

	return jobs
}

func (g *Generator) validateRenderJobs(jobs []renderJob) ([]string, error) {
	outputPaths := make([]string, 0, len(jobs))
	seenOutputPaths := make(map[string]struct{}, len(jobs))
	for _, job := range jobs {
		if _, exists := g.templates[job.TemplateName]; !exists {
			return nil, fmt.Errorf(
				"render template %q for class %q: template is not loaded",
				job.TemplateName,
				job.Context.Class.Name,
			)
		}
		if _, exists := seenOutputPaths[job.OutputPath]; exists {
			return nil, fmt.Errorf("duplicate output path %q", job.OutputPath)
		}
		seenOutputPaths[job.OutputPath] = struct{}{}
		outputPaths = append(outputPaths, job.OutputPath)
	}
	sort.Strings(outputPaths)
	return outputPaths, nil
}

func (g *Generator) renderTemplates(jobs []renderJob) error {
	workerCount := runtime.GOMAXPROCS(0)
	if workerCount > len(jobs) {
		workerCount = len(jobs)
	}
	if workerCount == 0 {
		return nil
	}

	jobChannel := make(chan renderJob)
	errorChannel := make(chan error, len(jobs))
	var workers sync.WaitGroup
	for range workerCount {
		workers.Add(1)
		go func() {
			defer workers.Done()
			for job := range jobChannel {
				if err := g.renderTemplate(job.TemplateName, filepath.FromSlash(job.OutputPath), job.Context); err != nil {
					errorChannel <- fmt.Errorf("render template %q for class %q: %w", job.TemplateName, job.Context.Class.Name, err)
				}
			}
		}()
	}

	for _, job := range jobs {
		jobChannel <- job
	}
	close(jobChannel)
	workers.Wait()
	close(errorChannel)

	var renderErrors []error
	for err := range errorChannel {
		renderErrors = append(renderErrors, err)
	}
	if len(renderErrors) > 0 {
		sort.Slice(renderErrors, func(i, j int) bool {
			return renderErrors[i].Error() < renderErrors[j].Error()
		})
		return errors.Join(renderErrors...)
	}

	genLogger.Infof("Successfully rendered %d template files.", len(jobs))
	return nil
}

func (g *Generator) renderTemplate(templateName, outputPath string, context TemplateContext) error {
	var rendered bytes.Buffer
	if err := g.templates[templateName].Execute(&rendered, context); err != nil {
		return fmt.Errorf("execute: %w", err)
	}

	contents, err := formatRenderedTemplate(outputPath, rendered.Bytes())
	if err != nil {
		return err
	}
	marker, err := generatedMarkerForPath(outputPath)
	if err != nil {
		return err
	}
	if firstLine(string(contents)) != marker {
		return fmt.Errorf("generated marker is not the first line")
	}

	if err := os.MkdirAll(filepath.Dir(outputPath), 0o755); err != nil {
		return fmt.Errorf("create output directory for %q: %w", outputPath, err)
	}
	if err := os.WriteFile(outputPath, contents, 0o644); err != nil {
		return fmt.Errorf("write output %q: %w", outputPath, err)
	}

	genLogger.Debugf("Successfully rendered template %s to: %s.", templateName, outputPath)
	return nil
}

func formatRenderedTemplate(outputPath string, contents []byte) ([]byte, error) {
	switch filepath.Ext(outputPath) {
	case ".go":
		formatted, err := format.Source(contents)
		if err != nil {
			return nil, fmt.Errorf("format Go output %q: %w", outputPath, err)
		}
		return formatted, nil
	case ".tf":
		if _, diagnostics := hclsyntax.ParseConfig(contents, outputPath, hcl.InitialPos); diagnostics.HasErrors() {
			return nil, fmt.Errorf("parse Terraform output %q: %s", outputPath, diagnostics.Error())
		}
		return hclwrite.Format(contents), nil
	case ".md":
		return contents, nil
	default:
		return nil, fmt.Errorf("output %q has unsupported format", outputPath)
	}
}

func generatedMarkerForPath(filePath string) (string, error) {
	outputName := strings.TrimSuffix(filePath, ".tmpl")
	switch filepath.Ext(outputName) {
	case ".go":
		return "// " + fmt.Sprintf(generatedMarkerFormat, "Code"), nil
	case ".md":
		return "<!-- " + fmt.Sprintf(generatedMarkerFormat, "Documentation") + " -->", nil
	case ".tf":
		return "# " + fmt.Sprintf(generatedMarkerFormat, "Configuration"), nil
	default:
		return "", fmt.Errorf("file %q has unsupported output format", filePath)
	}
}

func firstLine(contents string) string {
	line, _, _ := strings.Cut(contents, "\n")
	return strings.TrimSuffix(line, "\r")
}
