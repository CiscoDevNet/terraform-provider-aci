const (
	templatePath          = "gen/templates"
	exampleFilesPath      = "gen/definitions/example_files"
	generatedMarkerFormat = `%s generated by "gen/generator.go"; DO NOT EDIT.`

	modelTemplateName    = "model.go.tmpl"
	modelOutputDirectory = "internal/provider/models"

	indexTemplateName   = "index.md.tmpl"
	indexOutputPath     = "docs/index.md"
	providerExamplePath = "examples/provider/provider.tf"

	providerExampleTemplateName       = "provider_example.tf.tmpl"
	resourceExamplesOutputDirectory   = "examples/resources"
	datasourceExamplesOutputDirectory = "examples/data-sources"
	providerExampleOutputName         = "provider.tf"
	resourceExampleTemplateName       = "resource_example.tf.tmpl"
	resourceExampleOutputName         = "resource.tf"
	resourceFullExampleTemplateName   = "resource_example_all_attributes.tf.tmpl"
	resourceFullExampleOutputName     = "resource-all-attributes.tf"
	datasourceExampleTemplateName     = "datasource_example.tf.tmpl"
	datasourceExampleOutputName       = "data-source.tf"

	annotationUnsupportedTemplateName = "annotation_unsupported.go.tmpl"
	annotationUnsupportedOutputPath   = "internal/provider/annotation_unsupported.go"
)

var genLogger = logger.InitializeLogger()

// Generator owns template loading, output planning, rendering, and manifest replacement.
type Generator struct {
	dataStore       *data.DataStore
	providerExample string
	templates       map[string]*texttemplate.Template
}

// TemplateContext exposes normalized class or global data directly to every template.
type TemplateContext struct {
	Class           *data.Class
	DataStore       *data.DataStore
	ProviderExample string
}

// renderJob binds one loaded template to its destination and normalized input.
type renderJob struct {
	TemplateName string
	OutputPath   string
	Context      TemplateContext
	// Refresh-only outputs are rendered normally but are not owned by the managed-files manifest.
	RefreshOnly bool
}

// exampleFileJob carries a validated example file through the same manifest-owned transaction.
type exampleFileJob struct {
	SourcePath string
	OutputPath string
	Contents   []byte
}

// NewGenerator loads all static inputs needed before generation can modify managed files.
func NewGenerator(dataStore *data.DataStore) (*Generator, error) {
	if dataStore == nil {
		return nil, fmt.Errorf("initialize template generator: data store is nil")
	}

	providerExample, err := os.ReadFile(providerExamplePath)
	if err != nil {
		return nil, fmt.Errorf("read provider example %q: %w", providerExamplePath, err)
	}

	generator := &Generator{
		dataStore:       dataStore,
		providerExample: strings.TrimRight(string(providerExample), "\r\n"),
	}
	if err := generator.loadTemplates(); err != nil {
		return nil, err
	}

	return generator, nil
}

func (g *Generator) loadTemplates() error {
	genLogger.Debugf("Loading templates from: %s.", templatePath)
	entries, err := os.ReadDir(templatePath)
	if err != nil {
		return fmt.Errorf("read template directory %q: %w", templatePath, err)
	}

	g.templates = make(map[string]*texttemplate.Template)
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".tmpl") {
			continue
		}

		path := filepath.Join(templatePath, entry.Name())
		genLogger.Debugf("Loading template: %s.", path)
		contents, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("read template %q: %w", path, err)
		}

		parsedTemplate, err := parseTemplate(entry.Name(), contents)
		if err != nil {
			return fmt.Errorf("load template %q: %w", path, err)
		}
		g.templates[entry.Name()] = parsedTemplate
		genLogger.Debugf("Successfully loaded template: %s.", path)
	}

	genLogger.Debugf("Successfully loaded %d templates.", len(g.templates))
	return nil
}

func parseTemplate(templateName string, contents []byte) (*texttemplate.Template, error) {
	if err := validateGeneratedMarker(templateName, contents); err != nil {
		return nil, err
	}

	parsedTemplate, err := texttemplate.New(templateName).Parse(string(contents))
	if err != nil {
		return nil, fmt.Errorf("parse template: %w", err)
	}
	return parsedTemplate, nil
}

// Generate replaces the complete manifest-owned output set in one run.
func (g *Generator) Generate() error {
	genLogger.Trace("Building template render jobs")
	jobs := g.buildRenderJobs()
	genLogger.Trace("Building template render jobs complete")
	genLogger.Trace("Building example file jobs")
	// Read example files during preflight so a missing source cannot delete valid prior output.
	exampleFileJobs, err := g.buildResourceExampleFileJobs()
	if err != nil {
		return fmt.Errorf("build example file jobs: %w", err)
	}
	genLogger.Trace("Building example file jobs complete")

	genLogger.Trace("Validating template render jobs")
	plannedFiles, err := g.validateRenderJobs(jobs)
	if err != nil {
		return fmt.Errorf("validate render jobs: %w", err)
	}
	for _, job := range exampleFileJobs {
		plannedFiles = append(plannedFiles, job.OutputPath)
	}
	plannedManifest := manifest.New(plannedFiles)
	genLogger.Trace("Validating template render jobs complete")

	genLogger.Trace("Loading managed files")
	managedFiles, err := manifest.Load()
	if err != nil {
		return fmt.Errorf("load managed files: %w", err)
	}
	genLogger.Trace("Loading managed files complete")

	genLogger.Trace("Deleting managed files")
	if err := managedFiles.DeleteManagedFiles(); err != nil {
		return fmt.Errorf("delete managed files: %w", err)
	}
	genLogger.Trace("Deleting managed files complete")

	genLogger.Trace("Rendering templates")
	generationErr := g.renderTemplates(jobs)
	if generationErr == nil {
		genLogger.Trace("Rendering templates complete")
		genLogger.Trace("Copying example files")
		generationErr = writeExampleFiles(exampleFileJobs)
		if generationErr == nil {
			genLogger.Trace("Copying example files complete")
		}
	}
	if generationErr != nil {
		genLogger.Trace("Cleaning up outputs after failed generation")
		if cleanupErr := plannedManifest.DeleteManagedFiles(); cleanupErr != nil {
			return errors.Join(
				generationErr,
				fmt.Errorf("clean up outputs after failed generation: %w", cleanupErr),
			)
		}
		genLogger.Trace("Cleaning up outputs after failed generation complete")
		return generationErr
	}

	genLogger.Trace("Writing managed files")
	if err := plannedManifest.Write(); err != nil {
		return fmt.Errorf("write managed files: %w", err)
	}
	genLogger.Trace("Writing managed files complete")

	return nil
}

func (g *Generator) buildRenderJobs() []renderJob {
	jobs := g.buildModelRenderJobs()
	jobs = append(jobs, g.buildIndexRenderJob())
	jobs = append(jobs, g.buildProviderExampleRenderJobs()...)
	jobs = append(jobs, g.buildResourceExampleRenderJobs()...)
	jobs = append(jobs, g.buildResourceFullExampleRenderJobs()...)
	jobs = append(jobs, g.buildDatasourceExampleRenderJobs()...)
	if g.dataStore.UnsupportedAnnotationClasses != nil {
		jobs = append(jobs, g.buildAnnotationUnsupportedRenderJob())
	}
	return jobs
}

func (g *Generator) buildResourceExampleFileJobs() ([]exampleFileJob, error) {
	// Resolve each class file to its final example path and retain its contents until
	// template rendering has completed successfully.
	classNames := g.sortedClassNames()

	var jobs []exampleFileJob
	for _, className := range classNames {
		class := g.dataStore.Classes[className]
		if !class.HasResourceArtifact() {
			continue
		}
		for _, fileName := range class.ResourceExamples.Files {
			sourcePath := pathpkg.Join(exampleFilesPath, fileName)
			contents, err := os.ReadFile(filepath.FromSlash(sourcePath))
			if err != nil {
				return nil, fmt.Errorf("read example file %q: %w", sourcePath, err)
			}
			jobs = append(jobs, exampleFileJob{
				SourcePath: sourcePath,
				OutputPath: pathpkg.Join(resourceExamplesOutputDirectory, "aci_"+class.ResourceName, fileName),
				Contents:   contents,
			})
		}
	}
	return jobs, nil
}

func (g *Generator) buildResourceExampleRenderJobs() []renderJob {
	return g.buildClassExampleRenderJobs(
		data.ResourceArtifact,
		resourceExampleTemplateName,
		resourceExamplesOutputDirectory,
		resourceExampleOutputName,
	)
}

func (g *Generator) buildResourceFullExampleRenderJobs() []renderJob {
	// Omit an all-attributes file when it duplicates the minimum example at the
	// data-model level.
	jobs := g.buildClassExampleRenderJobs(
		data.ResourceArtifact,
		resourceFullExampleTemplateName,
		resourceExamplesOutputDirectory,
		resourceFullExampleOutputName,
	)

	distinctJobs := make([]renderJob, 0, len(jobs))
	for _, job := range jobs {
		if job.Context.Class.ResourceExamples.HasDistinctFullExample() {
			distinctJobs = append(distinctJobs, job)
		}
	}
	return distinctJobs
}

func (g *Generator) buildDatasourceExampleRenderJobs() []renderJob {
	return g.buildClassExampleRenderJobs(
		data.DatasourceArtifact,
		datasourceExampleTemplateName,
		datasourceExamplesOutputDirectory,
		datasourceExampleOutputName,
	)
}

func (g *Generator) buildClassExampleRenderJobs(artifact data.ArtifactEnum, templateName, outputDirectory, outputName string) []renderJob {
	// Apply common ordering and artifact filtering to resource and datasource examples.
	classNames := g.sortedClassNames()

	jobs := make([]renderJob, 0, len(classNames))
	for _, className := range classNames {
		class := g.dataStore.Classes[className]
		if artifact == data.ResourceArtifact && !class.HasResourceArtifact() {
			continue
		}
		if artifact == data.DatasourceArtifact && !class.HasDatasourceArtifact() {
			continue
		}
		jobs = append(jobs, renderJob{
			TemplateName: templateName,
			OutputPath:   pathpkg.Join(outputDirectory, "aci_"+class.ResourceName, outputName),
			Context:      TemplateContext{Class: &class, DataStore: g.dataStore},
		})
	}
	return jobs
}

func (g *Generator) buildIndexRenderJob() renderJob {
	return renderJob{
		TemplateName: indexTemplateName,
		OutputPath:   indexOutputPath,
		Context: TemplateContext{
			DataStore:       g.dataStore,
			ProviderExample: g.providerExample,
		},
	}
}

func (g *Generator) buildAnnotationUnsupportedRenderJob() renderJob {
	return renderJob{
		TemplateName: annotationUnsupportedTemplateName,
		OutputPath:   annotationUnsupportedOutputPath,
		Context:      TemplateContext{DataStore: g.dataStore},
		RefreshOnly:  true,
	}
}

func (g *Generator) buildModelRenderJobs() []renderJob {
	classNames := g.sortedClassNames()

	jobs := make([]renderJob, 0, len(classNames))
	for _, className := range classNames {
		class := g.dataStore.Classes[className]
		outputPath := pathpkg.Join(modelOutputDirectory, class.Name.String()+".go")
		jobs = append(jobs, renderJob{
			TemplateName: modelTemplateName,
			OutputPath:   outputPath,
			Context: TemplateContext{
				Class:     &class,
				DataStore: g.dataStore,
			},
		})
	}

	return jobs
}

func (g *Generator) buildProviderExampleRenderJobs() []renderJob {
	classNames := g.sortedClassNames()

	jobs := make([]renderJob, 0, len(classNames)*2)
	for _, className := range classNames {
		class := g.dataStore.Classes[className]
		if class.HasResourceArtifact() {
			jobs = append(jobs, renderJob{
				TemplateName: providerExampleTemplateName,
				OutputPath: pathpkg.Join(
					resourceExamplesOutputDirectory,
					"aci_"+class.ResourceName,
					providerExampleOutputName,
				),
			})
		}
		if class.HasDatasourceArtifact() {
			jobs = append(jobs, renderJob{
				TemplateName: providerExampleTemplateName,
				OutputPath: pathpkg.Join(
					datasourceExamplesOutputDirectory,
					"aci_"+class.ResourceName,
					providerExampleOutputName,
				),
			})
		}
	}

	sort.Slice(jobs, func(i, j int) bool {
		return jobs[i].OutputPath < jobs[j].OutputPath
	})
	return jobs
}

func (g *Generator) sortedClassNames() []string {
	classNames := make([]string, 0, len(g.dataStore.Classes))
	for className := range g.dataStore.Classes {
		classNames = append(classNames, className)
	}
	sort.Strings(classNames)
	return classNames
}

func (g *Generator) validateRenderJobs(jobs []renderJob) ([]string, error) {
	managedOutputPaths := make([]string, 0, len(jobs))
	seenOutputPaths := make(map[string]struct{}, len(jobs))
	for _, job := range jobs {
		if _, exists := g.templates[job.TemplateName]; !exists {
			return nil, fmt.Errorf(
				"render template %q to %q: template is not loaded",
				job.TemplateName,
				job.OutputPath,
			)
		}
		if _, exists := seenOutputPaths[job.OutputPath]; exists {
			return nil, fmt.Errorf("duplicate output path %q", job.OutputPath)
		}
		seenOutputPaths[job.OutputPath] = struct{}{}
		if !job.RefreshOnly {
			managedOutputPaths = append(managedOutputPaths, job.OutputPath)
		}
	}
	sort.Strings(managedOutputPaths)
	return managedOutputPaths, nil
}

func (g *Generator) renderTemplates(jobs []renderJob) error {
	workerCount := runtime.GOMAXPROCS(0)
	if workerCount > len(jobs) {
		workerCount = len(jobs)
	}
	if workerCount == 0 {
		return nil
	}

	jobChannel := make(chan renderJob)
	errorChannel := make(chan error, len(jobs))
	var workers sync.WaitGroup
	for range workerCount {
		workers.Add(1)
		go func() {
			defer workers.Done()
			for job := range jobChannel {
				if err := g.renderTemplate(job.TemplateName, filepath.FromSlash(job.OutputPath), job.Context); err != nil {
					errorChannel <- fmt.Errorf("render template %q to %q: %w", job.TemplateName, job.OutputPath, err)
				}
			}
		}()
	}

	for _, job := range jobs {
		jobChannel <- job
	}
	close(jobChannel)
	workers.Wait()
	close(errorChannel)

	var renderErrors []error
	for err := range errorChannel {
		renderErrors = append(renderErrors, err)
	}
	if len(renderErrors) > 0 {
		sort.Slice(renderErrors, func(i, j int) bool {
			return renderErrors[i].Error() < renderErrors[j].Error()
		})
		return errors.Join(renderErrors...)
	}

	genLogger.Infof("Successfully rendered %d template files.", len(jobs))
	for _, summary := range formatTemplateRenderSummaries(jobs) {
		genLogger.Infof("%s", summary)
	}
	return nil
}

func formatTemplateRenderSummaries(jobs []renderJob) []string {
	counts := make(map[string]int)
	for _, job := range jobs {
		counts[job.TemplateName]++
	}

	templateNames := make([]string, 0, len(counts))
	for templateName := range counts {
		templateNames = append(templateNames, templateName)
	}
	sort.Strings(templateNames)

	summaries := make([]string, 0, len(templateNames))
	for _, templateName := range templateNames {
		fileLabel := "files"
		if counts[templateName] == 1 {
			fileLabel = "file"
		}
		summaries = append(summaries, fmt.Sprintf("Rendered %d %s using template %s.", counts[templateName], fileLabel, templateName))
	}
	return summaries
}

func (g *Generator) renderTemplate(templateName, outputPath string, context TemplateContext) error {
	var rendered bytes.Buffer
	if err := g.templates[templateName].Execute(&rendered, context); err != nil {
		return fmt.Errorf("execute: %w", err)
	}

	contents, err := formatRenderedTemplate(outputPath, rendered.Bytes())
	if err != nil {
		return err
	}
	if err := validateGeneratedMarker(outputPath, contents); err != nil {
		return fmt.Errorf("validate generated marker: %w", err)
	}

	if err := writeOutputFile(outputPath, contents); err != nil {
		return err
	}

	genLogger.Debugf("Successfully rendered template %s to: %s.", templateName, outputPath)
	return nil
}

func writeExampleFiles(jobs []exampleFileJob) error {
	// Copy non-template files that cannot carry a generated marker.
	for _, job := range jobs {
		outputPath := filepath.FromSlash(job.OutputPath)
		if err := writeOutputFile(outputPath, job.Contents); err != nil {
			return fmt.Errorf("copy example file %q to %q: %w", job.SourcePath, job.OutputPath, err)
		}
		genLogger.Debugf("Successfully copied example file %s to: %s.", job.SourcePath, job.OutputPath)
	}
	if len(jobs) > 0 {
		genLogger.Infof("Successfully copied %d example files.", len(jobs))
	}
	return nil
}

func writeOutputFile(outputPath string, contents []byte) error {
	// Give rendered templates and copied example files identical directory creation,
	// permissions, and error handling.
	if err := os.MkdirAll(filepath.Dir(outputPath), 0o755); err != nil {
		return fmt.Errorf("create output directory for %q: %w", outputPath, err)
	}
	if err := os.WriteFile(outputPath, contents, 0o644); err != nil {
		return fmt.Errorf("write output %q: %w", outputPath, err)
	}
	return nil
}

func formatRenderedTemplate(outputPath string, contents []byte) ([]byte, error) {
	switch filepath.Ext(outputPath) {
	case ".go":
		formatted, err := format.Source(contents)
		if err != nil {
			return nil, fmt.Errorf("format Go output %q: %w", outputPath, err)
		}
		return formatted, nil
	case ".tf":
		if _, diagnostics := hclsyntax.ParseConfig(contents, outputPath, hcl.InitialPos); diagnostics.HasErrors() {
			return nil, fmt.Errorf("parse Terraform output %q: %s", outputPath, diagnostics.Error())
		}
		return hclwrite.Format(contents), nil
	case ".md":
		return contents, nil
	default:
		return nil, fmt.Errorf("output %q has unsupported format", outputPath)
	}
}

func generatedMarkerForPath(filePath string) (string, error) {
	outputName := strings.TrimSuffix(filePath, ".tmpl")
	switch filepath.Ext(outputName) {
	case ".go":
		return "// " + fmt.Sprintf(generatedMarkerFormat, "Code"), nil
	case ".md":
		return "# " + fmt.Sprintf(generatedMarkerFormat, "Documentation"), nil
	case ".tf":
		return "# " + fmt.Sprintf(generatedMarkerFormat, "Configuration"), nil
	default:
		return "", fmt.Errorf("file %q has unsupported output format", filePath)
	}
}

func validateGeneratedMarker(filePath string, contents []byte) error {
	marker, err := generatedMarkerForPath(filePath)
	if err != nil {
		return err
	}

	contentsString := string(contents)
	outputName := strings.TrimSuffix(filePath, ".tmpl")
	if filepath.Ext(outputName) == ".md" {
		frontMatter, remainingContents, found := strings.Cut(contentsString, "\n")
		if strings.TrimSuffix(frontMatter, "\r") != "---" || !found || firstLine(remainingContents) != marker {
			return fmt.Errorf("must start with YAML front matter delimiter followed by %q", marker)
		}
		return nil
	}

	if firstLine(contentsString) != marker {
		return fmt.Errorf("must start with %q", marker)
	}
	return nil
}

func firstLine(contents string) string {
	line, _, _ := strings.Cut(contents, "\n")
	return strings.TrimSuffix(line, "\r")
}
