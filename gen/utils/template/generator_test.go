func TestBuildModelRenderJobs(t *testing.T) {
	dataStore := &data.DataStore{Classes: map[string]data.Class{
		"fvRsTenantMonPol": testClass(t, "fvRsTenantMonPol"),
		"fvTenant":         testClass(t, "fvTenant", data.ResourceArtifact, data.DatasourceArtifact),
	}}
	generator := &Generator{dataStore: dataStore}

	jobs := generator.buildModelRenderJobs()
	if len(jobs) != 2 {
		t.Fatalf("expected two jobs, got %d", len(jobs))
	}
	expectedPaths := []string{
		"internal/provider/models/fvRsTenantMonPol.go",
		"internal/provider/models/fvTenant.go",
	}
	actualPaths := []string{jobs[0].OutputPath, jobs[1].OutputPath}
	if !reflect.DeepEqual(actualPaths, expectedPaths) {
		t.Fatalf("model output paths %#v, expected %#v", actualPaths, expectedPaths)
	}
	for _, job := range jobs {
		if job.TemplateName != modelTemplateName {
			t.Fatalf("unexpected template name %q", job.TemplateName)
		}
		if job.Context.Class == nil || job.Context.DataStore != dataStore {
			t.Fatalf("incomplete template context: %#v", job.Context)
		}
	}
}

func TestModelTemplateArtifacts(t *testing.T) {
	generator := loadActiveGenerator(t, &data.DataStore{})
	modelTemplate := generator.templates[modelTemplateName]

	testCases := []struct {
		name            string
		artifacts       []data.ArtifactEnum
		resourceModel   bool
		dataSourceModel bool
	}{
		{name: "child only"},
		{
			name:          "resource only",
			artifacts:     []data.ArtifactEnum{data.ResourceArtifact},
			resourceModel: true,
		},
		{
			name:            "datasource only",
			artifacts:       []data.ArtifactEnum{data.DatasourceArtifact},
			dataSourceModel: true,
		},
		{
			name: "resource and datasource",
			artifacts: []data.ArtifactEnum{
				data.ResourceArtifact,
				data.DatasourceArtifact,
			},
			resourceModel:   true,
			dataSourceModel: true,
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			class := testClass(t, "fvTenant", testCase.artifacts...)

			var rendered bytes.Buffer
			if err := modelTemplate.Execute(&rendered, TemplateContext{
				Class:     &class,
				DataStore: generator.dataStore,
			}); err != nil {
				t.Fatalf("execute model template: %v", err)
			}

			formatted, err := formatRenderedTemplate("fvTenant.go", rendered.Bytes())
			if err != nil {
				t.Fatalf("format model template: %v", err)
			}

			contents := string(formatted)
			if !strings.Contains(contents, "type FvTenantModel struct") {
				t.Fatal("shared model was not rendered")
			}

			resourceType := "type FvTenantResourceModel struct"
			if actual := strings.Contains(contents, resourceType); actual != testCase.resourceModel {
				t.Fatalf("resource model presence %t, expected %t", actual, testCase.resourceModel)
			}

			dataSourceType := "type FvTenantDataSourceModel struct"
			if actual := strings.Contains(contents, dataSourceType); actual != testCase.dataSourceModel {
				t.Fatalf("data source model presence %t, expected %t", actual, testCase.dataSourceModel)
			}
		})
	}
}

func TestGeneratedModelBuildRN(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name       string
		build      func() string
		expectedRN string
	}{
		{
			name: "static RN",
			build: func() string {
				model := models.FvAccPModel{}
				return model.BuildRN()
			},
			expectedRN: "accp",
		},
		{
			name: "single identifier",
			build: func() string {
				model := models.FvTenantModel{Name: types.StringValue("example")}
				return model.BuildRN()
			},
			expectedRN: "tn-example",
		},
		{
			name: "multi identifier placeholder order",
			build: func() string {
				model := models.FvRsBDToNetflowMonitorPolModel{
					FltType:                 types.StringValue("ipv4"),
					TnNetflowMonitorPolName: types.StringValue("monitor"),
				}
				return model.BuildRN()
			},
			expectedRN: "rsBDToNetflowMonitorPol-[monitor]-ipv4",
		},
		{
			name: "custom identifier normalization and fixed path",
			build: func() string {
				model := models.FvEpIpTagModel{
					CtxName: types.StringValue("vrf"),
					Ip:      customTypes.NewIPAddressStringValue("2001:0db8::1"),
				}
				return model.BuildRN()
			},
			expectedRN: "eptags/epiptag-[2001:db8::1]-vrf",
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			rn := testCase.build()
			if rn != testCase.expectedRN {
				t.Fatalf("RN %q, expected %q", rn, testCase.expectedRN)
			}
		})
	}
}

func TestRenderTemplates(t *testing.T) {
	dataStore := &data.DataStore{Classes: map[string]data.Class{}}
	templateName := "test.go.tmpl"
	loadedTemplate := texttemplate.Must(texttemplate.New(templateName).Parse(testCodeMarker + `
package models

type {{ .Class.Name.Capitalized }}Model struct{}
`))
	generator := &Generator{
		dataStore: dataStore,
		templates: map[string]*texttemplate.Template{templateName: loadedTemplate},
	}
	classes := []data.Class{
		testClass(t, "fvTenant"),
		testClass(t, "fvAp"),
	}
	jobs := make([]renderJob, 0, len(classes))
	for index := range classes {
		class := &classes[index]
		dataStore.Classes[class.Name.String()] = *class
		jobs = append(jobs, renderJob{
			TemplateName: templateName,
			OutputPath:   filepath.ToSlash(filepath.Join(modelOutputDirectory, class.Name.String()+".go")),
			Context:      TemplateContext{Class: class, DataStore: dataStore},
		})
	}
	repositoryRoot := t.TempDir()
	t.Chdir(repositoryRoot)

	generatedFiles, err := generator.validateRenderJobs(jobs)
	if err != nil {
		t.Fatalf("validate render jobs: %v", err)
	}
	if err := generator.renderTemplates(jobs); err != nil {
		t.Fatalf("render templates: %v", err)
	}
	expectedFiles := []string{
		"internal/provider/models/fvAp.go",
		"internal/provider/models/fvTenant.go",
	}
	if !reflect.DeepEqual(generatedFiles, expectedFiles) {
		t.Fatalf("generated files %#v, expected %#v", generatedFiles, expectedFiles)
	}

	for _, generatedFile := range generatedFiles {
		contents, err := os.ReadFile(filepath.Join(repositoryRoot, filepath.FromSlash(generatedFile)))
		if err != nil {
			t.Fatalf("read rendered template %q: %v", generatedFile, err)
		}
		if firstLine(string(contents)) != testCodeMarker {
			t.Fatalf("rendered template %q is missing its generated marker", generatedFile)
		}
		className := strings.TrimSuffix(filepath.Base(generatedFile), ".go")
		class := dataStore.Classes[className]
		if !strings.Contains(string(contents), "type "+class.Name.Capitalized()+"Model struct{}") {
			t.Fatalf("rendered template %q does not contain its class model", generatedFile)
		}
	}
}

