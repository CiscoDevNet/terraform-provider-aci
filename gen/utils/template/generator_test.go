func TestGenerateCleansOutputsAfterRenderFailure(t *testing.T) {
	repositoryRoot := t.TempDir()
	t.Chdir(repositoryRoot)

	previousOutputPath := filepath.FromSlash("internal/provider/models/fvPrevious.go")
	if err := os.MkdirAll(filepath.Dir(previousOutputPath), 0o755); err != nil {
		t.Fatalf("create previous output directory: %v", err)
	}
	if err := os.WriteFile(previousOutputPath, []byte("previous generated output\n"), 0o600); err != nil {
		t.Fatalf("write previous managed output: %v", err)
	}
	if err := os.MkdirAll("gen", 0o755); err != nil {
		t.Fatalf("create manifest directory: %v", err)
	}
	manifestContents := []byte("{\n  \"directories\": {\n    \"internal/provider/models\": [\n      \"fvPrevious.go\"\n    ]\n  }\n}\n")
	if err := os.WriteFile("gen/managed_files.json", manifestContents, 0o600); err != nil {
		t.Fatalf("write managed-files manifest: %v", err)
	}

	failedTemplate := texttemplate.Must(texttemplate.New(modelTemplateName).Parse(testCodeMarker + `
{{ if eq .Class.Name.String "fvBroken" -}}
package
{{ else -}}
package models

type {{ .Class.Name.Capitalized }}Model struct{}
{{ end -}}
`))
	indexTemplate := texttemplate.Must(texttemplate.New(indexTemplateName).Parse("---\n" + testDocumentationMarker + `
layout: "aci"
---

{{ .ProviderExample }}
`))
	classes := map[string]data.Class{
		"fvBroken": testClass(t, "fvBroken"),
		"fvTenant": testClass(t, "fvTenant"),
	}
	generator := &Generator{
		dataStore:       &data.DataStore{Classes: classes},
		providerExample: `provider "aci" {}`,
		templates: map[string]*texttemplate.Template{
			modelTemplateName: failedTemplate,
			indexTemplateName: indexTemplate,
		},
	}

	err := generator.Generate()
	if err == nil || !strings.Contains(err.Error(), "format Go output") {
		t.Fatalf("expected rendered Go formatting error, got %v", err)
	}

	for className := range classes {
		outputPath := filepath.Join(modelOutputDirectory, className+".go")
		if _, statErr := os.Stat(outputPath); !os.IsNotExist(statErr) {
			t.Fatalf("expected attempted output %q to be absent, got %v", outputPath, statErr)
		}
	}
	if _, statErr := os.Stat(previousOutputPath); !os.IsNotExist(statErr) {
		t.Fatalf("expected previous managed output to be deleted, got %v", statErr)
	}
	actualManifestContents, readErr := os.ReadFile("gen/managed_files.json")
	if readErr != nil {
		t.Fatalf("read retained managed-files manifest: %v", readErr)
	}
	if !reflect.DeepEqual(actualManifestContents, manifestContents) {
		t.Fatalf("managed-files manifest changed from %q to %q", manifestContents, actualManifestContents)
	}
}

