const (
	testCodeMarker          = `// Code generated by "gen/generator.go"; DO NOT EDIT.`
	testDocumentationMarker = `<!-- Documentation generated by "gen/generator.go"; DO NOT EDIT. -->`
	testConfigurationMarker = `# Configuration generated by "gen/generator.go"; DO NOT EDIT.`
)

func TestParseTemplateSupportsOutputFormats(t *testing.T) {
	templates := map[string]string{
		"model.go.tmpl":    testCodeMarker + "\n",
		"resource.md.tmpl": testDocumentationMarker + "\n",
		"example.tf.tmpl":  testConfigurationMarker + "\n",
	}

	for name, expected := range templates {
		loadedTemplate, err := parseTemplate(name, []byte(expected))
		if err != nil {
			t.Fatalf("parse template %q: %v", name, err)
		}

		var rendered bytes.Buffer
		if err := loadedTemplate.Execute(&rendered, nil); err != nil {
			t.Fatalf("execute template %q: %v", name, err)
		}
		if rendered.String() != expected {
			t.Fatalf("template %q rendered %q, expected %q", name, rendered.String(), expected)
		}
	}
}

