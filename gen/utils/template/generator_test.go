func TestGenerateAnnotationUnsupportedOnlyAfterRefresh(t *testing.T) {
	testCases := []struct {
		name                         string
		unsupportedAnnotationClasses []string
		expectExistingOutput         bool
	}{
		{
			name:                 "ordinary generation preserves existing output",
			expectExistingOutput: true,
		},
		{
			name:                         "refresh generation renders output",
			unsupportedAnnotationClasses: []string{"aaaConfig", "fvTenant"},
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			repositoryRoot := t.TempDir()
			t.Chdir(repositoryRoot)

			if err := os.MkdirAll(filepath.Dir(annotationUnsupportedOutputPath), 0o755); err != nil {
				t.Fatalf("create annotation output directory: %v", err)
			}
			existingContents := []byte("existing annotation output\n")
			if err := os.WriteFile(annotationUnsupportedOutputPath, existingContents, 0o600); err != nil {
				t.Fatalf("write existing annotation output: %v", err)
			}
			if err := os.MkdirAll("gen", 0o755); err != nil {
				t.Fatalf("create manifest directory: %v", err)
			}
			if err := os.WriteFile("gen/managed_files.json", []byte("{\n  \"directories\": {}\n}\n"), 0o600); err != nil {
				t.Fatalf("write managed-files manifest: %v", err)
			}

			modelTemplate := texttemplate.Must(texttemplate.New(modelTemplateName).Parse(testCodeMarker + `
package models

type {{ .Class.Name.Capitalized }}Model struct{}
`))
			annotationTemplate := texttemplate.Must(texttemplate.New(annotationUnsupportedTemplateName).Parse(testCodeMarker + `
package provider

func UnsupportedAnnotationClasses() []string {
	return []string{
		{{- range .DataStore.UnsupportedAnnotationClasses }}
		{{ printf "%q" . }},
		{{- end }}
	}
}
`))
			class := testClass(t, "fvTenant")
			dataStore := &data.DataStore{
				Classes:                      map[string]data.Class{"fvTenant": class},
				UnsupportedAnnotationClasses: testCase.unsupportedAnnotationClasses,
			}
			generator := &Generator{
				dataStore: dataStore,
				templates: map[string]*texttemplate.Template{
					modelTemplateName:                 modelTemplate,
					annotationUnsupportedTemplateName: annotationTemplate,
				},
			}

			if err := generator.Generate(); err != nil {
				t.Fatalf("generate templates: %v", err)
			}

			contents, err := os.ReadFile(annotationUnsupportedOutputPath)
			if err != nil {
				t.Fatalf("read annotation output: %v", err)
			}
			if testCase.expectExistingOutput {
				if !reflect.DeepEqual(contents, existingContents) {
					t.Fatalf("annotation output changed from %q to %q", existingContents, contents)
				}
			} else {
				for _, className := range testCase.unsupportedAnnotationClasses {
					if !strings.Contains(string(contents), `"`+className+`"`) {
						t.Fatalf("rendered annotation output does not contain class %q", className)
					}
				}
			}

			manifestContents, err := os.ReadFile("gen/managed_files.json")
			if err != nil {
				t.Fatalf("read managed-files manifest: %v", err)
			}
			if strings.Contains(string(manifestContents), "annotation_unsupported.go") {
				t.Fatalf("refresh-only annotation output was added to managed-files manifest: %s", manifestContents)
			}
		})
	}
}

func TestModelTemplateArtifacts(t *testing.T) {
	generator := loadActiveGenerator(t, &data.DataStore{})
	modelTemplate := generator.templates[modelTemplateName]

	testCases := []struct {
		name            string
		artifacts       []data.ArtifactEnum
		resourceModel   bool
		dataSourceModel bool
	}{
		{name: "child only"},
		{
			name:          "resource only",
			artifacts:     []data.ArtifactEnum{data.ResourceArtifact},
			resourceModel: true,
		},
		{
			name:            "datasource only",
			artifacts:       []data.ArtifactEnum{data.DatasourceArtifact},
			dataSourceModel: true,
		},
		{
			name: "resource and datasource",
			artifacts: []data.ArtifactEnum{
				data.ResourceArtifact,
				data.DatasourceArtifact,
			},
			resourceModel:   true,
			dataSourceModel: true,
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			class := testClass(t, "fvTenant", testCase.artifacts...)
			class.AllowDelete = true

			var rendered bytes.Buffer
			if err := modelTemplate.Execute(&rendered, TemplateContext{
				Class:     &class,
				DataStore: generator.dataStore,
			}); err != nil {
				t.Fatalf("execute model template: %v", err)
			}

			formatted, err := formatRenderedTemplate("fvTenant.go", rendered.Bytes())
			if err != nil {
				t.Fatalf("format model template: %v", err)
			}

			contents := string(formatted)
			if !strings.Contains(contents, "type FvTenantModel struct") {
				t.Fatal("shared model was not rendered")
			}
			if !strings.Contains(contents, "func (m *FvTenantModel) BuildDN() string") {
				t.Fatal("shared model DN builder was not rendered")
			}
			if !strings.Contains(contents, "func (m *FvTenantModel) BuildPayloadObject(") {
				t.Fatal("shared model payload object builder was not rendered")
			}
			if !strings.Contains(contents, "func (m *FvTenantModel) BuildNestedDeletePayloadObject(") {
				t.Fatal("shared model nested delete payload object builder was not rendered")
			}
			if !strings.Contains(contents, "func FvTenantModelFromObject(") {
				t.Fatal("shared model object decoder was not rendered")
			}
			responseDecoder := "func FvTenantModelFromResponse("
			if actual := strings.Contains(contents, responseDecoder); actual != (testCase.resourceModel || testCase.dataSourceModel) {
				t.Fatalf("response decoder presence %t, expected %t", actual, testCase.resourceModel || testCase.dataSourceModel)
			}

			resourceType := "type FvTenantResourceModel struct"
			if actual := strings.Contains(contents, resourceType); actual != testCase.resourceModel {
				t.Fatalf("resource model presence %t, expected %t", actual, testCase.resourceModel)
			}
			resourceIDSetter := "func (m *FvTenantResourceModel) SetIDFromDN(dn string)"
			if actual := strings.Contains(contents, resourceIDSetter); actual != testCase.resourceModel {
				t.Fatalf("resource ID setter presence %t, expected %t", actual, testCase.resourceModel)
			}
			resourceResponseSetter := "func (m *FvTenantResourceModel) SetFromResponse("
			if actual := strings.Contains(contents, resourceResponseSetter); actual != testCase.resourceModel {
				t.Fatalf("resource response setter presence %t, expected %t", actual, testCase.resourceModel)
			}

			dataSourceType := "type FvTenantDataSourceModel struct"
			if actual := strings.Contains(contents, dataSourceType); actual != testCase.dataSourceModel {
				t.Fatalf("data source model presence %t, expected %t", actual, testCase.dataSourceModel)
			}
			dataSourceIDSetter := "func (m *FvTenantDataSourceModel) SetIDFromDN(dn string)"
			if actual := strings.Contains(contents, dataSourceIDSetter); actual != testCase.dataSourceModel {
				t.Fatalf("data source ID setter presence %t, expected %t", actual, testCase.dataSourceModel)
			}
			dataSourceResponseSetter := "func (m *FvTenantDataSourceModel) SetFromResponse("
			if actual := strings.Contains(contents, dataSourceResponseSetter); actual != testCase.dataSourceModel {
				t.Fatalf("data source response setter presence %t, expected %t", actual, testCase.dataSourceModel)
			}
		})
	}
}

