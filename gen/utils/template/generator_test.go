func TestGeneratorRejectsInvalidTemplates(t *testing.T) {
	testCases := []struct {
		name          string
		templateName  string
		contents      string
		errorContains string
	}{
		{
			name:          "missing marker",
			templateName:  "model.go.tmpl",
			contents:      "package provider\n",
			errorContains: "must start with",
		},
		{
			name:          "marker is not first line",
			templateName:  "model.go.tmpl",
			contents:      "\n" + testCodeMarker + "\n",
			errorContains: "must start with",
		},
		{
			name:          "unsupported yaml template",
			templateName:  "testvars.yaml.tmpl",
			contents:      "# Configuration generated by generator\n",
			errorContains: "unsupported output format",
		},
		{
			name:          "invalid template syntax",
			templateName:  "model.go.tmpl",
			contents:      testCodeMarker + "\n{{",
			errorContains: "parse template",
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			_, err := parseTemplate(testCase.templateName, []byte(testCase.contents))
			if err == nil {
				t.Fatal("expected template loading to fail")
			}
			if !strings.Contains(err.Error(), testCase.errorContains) {
				t.Fatalf("error %q does not contain %q", err, testCase.errorContains)
			}
		})
	}
}

