func loadActiveGenerator(t *testing.T, dataStore *data.DataStore) *Generator {
	t.Helper()
	_, currentFile, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("determine generator test path")
	}
	repositoryRoot := filepath.Clean(filepath.Join(filepath.Dir(currentFile), "..", "..", ".."))
	t.Chdir(repositoryRoot)
	generator, err := NewGenerator(dataStore)
	if err != nil {
		t.Fatalf("initialize generator: %v", err)
	}
	return generator
}

