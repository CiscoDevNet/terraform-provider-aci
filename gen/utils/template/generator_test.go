type invalidTemplateInput struct {
	TemplateName string
	Contents     string
}

func TestGeneratorRejectsInvalidTemplates(t *testing.T) {
	testCases := []test.TestCase{
		{
			Name:     "test_missing_marker",
			Input:    invalidTemplateInput{TemplateName: "model.go.tmpl", Contents: "package provider\n"},
			Expected: "must start with",
		},
		{
			Name:     "test_marker_is_not_first_line",
			Input:    invalidTemplateInput{TemplateName: "model.go.tmpl", Contents: "\n" + testCodeMarker + "\n"},
			Expected: "must start with",
		},
		{
			Name:     "test_documentation_marker_is_not_after_front_matter_delimiter",
			Input:    invalidTemplateInput{TemplateName: "resource.md.tmpl", Contents: "---\nlayout: aci\n" + testDocumentationMarker + "\n"},
			Expected: "must start with YAML front matter delimiter followed by",
		},
		{
			Name:     "test_unsupported_yaml_template",
			Input:    invalidTemplateInput{TemplateName: "testvars.yaml.tmpl", Contents: "# Configuration generated by generator\n"},
			Expected: "unsupported output format",
		},
		{
			Name:     "test_invalid_template_syntax",
			Input:    invalidTemplateInput{TemplateName: "model.go.tmpl", Contents: testCodeMarker + "\n{{"},
			Expected: "parse template",
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.Name, func(t *testing.T) {
			input := testCase.Input.(invalidTemplateInput)
			expected := testCase.Expected.(string)
			_, err := parseTemplate(input.TemplateName, []byte(input.Contents))
			if err == nil {
				t.Fatal("expected template loading to fail")
			}
			if !strings.Contains(err.Error(), expected) {
				t.Fatalf("error %q does not contain %q", err, expected)
			}
		})
	}
}

